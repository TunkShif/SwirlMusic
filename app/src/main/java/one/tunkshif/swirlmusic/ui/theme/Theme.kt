    surfaceVariant = BrandSurfaceVariantLight,
    onSurfaceVariant = BrandOnSurfaceVariantLight,
    outline = BrandOutlineLight,
)

/**
 * Material 3 with the system wallpaper palette, falling back to the brand palette.
 *
 * Screenshot tests pass `dynamicColor = false` and pin `darkTheme`, otherwise the golden follows
 * whatever wallpaper the test machine has.
 */
@Composable
fun SwirlMusicTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    val colorScheme = when {
        dynamicColor -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> BrandDarkColorScheme
        else -> BrandLightColorScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        shapes = SwirlShapes,
        content = content,
    )
}
